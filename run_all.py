#!/usr/bin/env python3
"""Run the whole analysis in order and write results/summary.md.

    python run_all.py

Step 1 (digitising the figures) only runs if the figure images are present in
figures_src/; otherwise the digitised table already in data/ is used.
"""
from pathlib import Path
import subprocess
import sys
import pandas as pd

ROOT = Path(__file__).resolve().parent
STEPS = ["02_calibrate_and_anova.py", "03_effect_sizes.py", "04_mortality.py", "05_make_figures.py", "06_cross_species.py"]


def run(script):
    print(f"\n=== {script} ===")
    subprocess.run([sys.executable, str(ROOT / "scripts" / script)], check=True)


def signed(x):
    v = round(float(x))
    return "0" if v == 0 else f"{v:+d}"


def pct(row):
    return f"{signed(row['pct_change'])}% ({signed(row['pct_lo'])} to {signed(row['pct_hi'])})"


def write_summary():
    t = ROOT / "results" / "tables"
    es = pd.read_csv(t / "effect_sizes.csv")
    age = pd.read_csv(t / "control_age_change.csv")
    comp = pd.read_csv(t / "anova_vs_published.csv")
    mort = pd.read_csv(t / "mortality_tests.csv")
    lines = ["# Results summary", "",
             "Generated by `run_all.py`. Every number in the README comes from this file or the tables next to it.", ""]

    main, held = comp[comp.used_for_calibration], comp[~comp.used_for_calibration]
    lines += ["## 1. Does the digitised data reproduce the published ANOVA?", "",
              f"- Recomputed / published F, 15 main effects: {main.ratio_calibrated_to_published.min():.2f} to "
              f"{main.ratio_calibrated_to_published.max():.2f} (median {main.ratio_calibrated_to_published.median():.2f}).",
              f"- Five three-way interactions (not used for calibration): {held.ratio_calibrated_to_published.min():.2f} to "
              f"{held.ratio_calibrated_to_published.max():.2f} (median {held.ratio_calibrated_to_published.median():.2f}).",
              f"- With SEs read straight off the error bars the recomputed F was {(comp.F_raw_whiskers / comp.F_published).min():.2f} to "
              f"{(comp.F_raw_whiskers / comp.F_published).max():.2f} times the published value.", ""]

    lines += ["## 2. Control beetles, day 20 relative to day 10 (95% CI)", "", "| Marker | Male | Female |", "|---|---|---|"]
    for marker, g in age.groupby("marker", sort=False):
        g = g.set_index("sex")
        lines.append(f"| {marker} | {pct(g.loc['male'])} | {pct(g.loc['female'])} |")
    lines.append("")

    lines += ["## 3. Stressed vs same-day control, % change (95% CI); * = Holm-adjusted p < 0.05", ""]
    for phase, title in (("stress", "During stress (day 10)"), ("recovery", "After 10 days of recovery (day 20)")):
        lines += [f"### {title}", "", "| Marker | Cold, male | Cold, female | Heat, male | Heat, female |", "|---|---|---|---|---|"]
        for marker, g in es[es.phase == phase].groupby("marker", sort=False):
            g = g.set_index(["regime", "sex"])
            cells = [pct(g.loc[k]) + (" *" if g.loc[k, "significant_holm"] else "")
                     for k in (("cold", "male"), ("cold", "female"), ("heat", "male"), ("heat", "female"))]
            lines.append(f"| {marker} | " + " | ".join(cells) + " |")
        lines.append("")
    rec = es[es.phase == "recovery"]
    for marker in ("SOD", "CAT", "LPO", "triglycerides", "glucose"):
        g = rec[rec.marker == marker]
        lines.append(f"- {marker} after recovery: {int(g.significant_holm.sum())} of 4 groups differ from control "
                     f"(range {g['pct_change'].min():+.0f}% to {g['pct_change'].max():+.0f}%).")
    lines.append("")

    lines += ["## 4. Mortality", ""]
    for _, r in mort.iterrows():
        if pd.notna(r.get("estimate")):
            extra = f"; chi2 = {r.chi2:.2f}, p = {r.p:.2g}" if pd.notna(r.chi2) else ""
            lines.append(f"- {r.test}: {r.estimate:.2f} (95% CI {r.lo:.2f} to {r.hi:.2f}){extra}")
        else:
            lines.append(f"- {r.test}: chi2 = {r.chi2:.2f}, df = {int(r.df)}, p = {r.p:.2g}")
    (ROOT / "results" / "summary.md").write_text("\n".join(lines) + "\n")
    print("\nwrote results/summary.md")


if __name__ == "__main__":
    if (ROOT / "figures_src" / "fig2.png").exists():
        run("01_digitise_figures.py")
    else:
        print("figures_src/ is empty: using the digitised table already in data/")
    for step in STEPS:
        run(step)
    write_summary()
